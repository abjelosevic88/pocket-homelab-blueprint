// ---- the OpenAPI document ----
//
// Built from the endpoints a scan found: those in the code, and those of any
// OpenAPI/Swagger document in the folder (?source=code|spec|all, default
// all, one entry per method + path). It describes paths, methods, path
// parameters and where each handler is; request and response bodies are
// not guessed.

// omap is a JSON/YAML object that keeps its key order.
type omap []kv

type kv struct {
	k string
	v any
}

func (m omap) MarshalJSON() ([]byte, error) {
	var b bytes.Buffer
	b.WriteByte('{')
	for i, e := range m {
		if i > 0 {
			b.WriteByte(',')
		}
		k, _ := json.Marshal(e.k)
		b.Write(k)
		b.WriteByte(':')
		v, err := json.Marshal(e.v)
		if err != nil {
			return nil, err
		}
		b.Write(v)
	}
	b.WriteByte('}')
	return b.Bytes(), nil
}

var paramRe = regexp.MustCompile(`\{([^}/]+)\}`)

var httpMethods = []string{"get", "put", "post", "delete", "options", "head", "patch", "trace"}

func (s *Server) openAPI(res *analyze.Result, version, source string) omap {
	type op struct {
		method string
		e      analyze.Endpoint
	}
	byPath := map[string][]op{}
	seen := map[string]bool{}
	add := func(e analyze.Endpoint) {
		methods := []string{strings.ToLower(e.Method)}
		if e.Method == "ANY" || e.Method == "" {
			methods = []string{"get", "post", "put", "patch", "delete"}
		}
		for _, m := range methods {
			if !contains(httpMethods, m) {
				continue
			}
			key := m + " " + e.Path
			if seen[key] {
				continue
			}
			seen[key] = true
			byPath[e.Path] = append(byPath[e.Path], op{m, e})
		}
	}
	for _, pass := range []string{"spec", "code"} {
		if source != "" && source != "all" && source != pass {
			continue
		}
		for _, e := range res.Endpoints {
			if e.Source == pass && strings.HasPrefix(e.Path, "/") {
				add(e)
			}
		}
	}
	paths := make([]string, 0, len(byPath))
	for p := range byPath {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	ops := map[string]int{}
	tags := map[string]bool{}
	pathObj := omap{}
	for _, p := range paths {
		list := byPath[p]
		sort.Slice(list, func(i, j int) bool {
			return indexOf(httpMethods, list[i].method) < indexOf(httpMethods, list[j].method)
		})
		item := omap{}
		for _, o := range list {
			e := o.e
			opID := operationID(o.method, e)
			if ops[opID]++; ops[opID] > 1 {
				opID += strconv.Itoa(ops[opID])
			}
			obj := omap{{"operationId", opID}}
			summary := e.Summary
			if summary == "" && e.Handler != "" && !strings.Contains(e.Handler, "func") {
				summary = e.Handler
			}
			if summary != "" {
				obj = append(obj, kv{"summary", summary})
			}
			tag := e.Tag
			if tag == "" {
				tag = tagFor(e.Path)
			}
			if tag != "" {
				obj = append(obj, kv{"tags", []string{tag}})
				tags[tag] = true
			}
			if e.Method == "ANY" {
				obj = append(obj, kv{"description", "Registered for any method."})
			}
			var params []omap
			for _, m := range paramRe.FindAllStringSubmatch(p, -1) {
				params = append(params, omap{{"name", m[1]}, {"in", "path"}, {"required", true}, {"schema", omap{{"type", "string"}}}})
			}
			if len(params) > 0 {
				obj = append(obj, kv{"parameters", params})
			}
			if o.method == "post" || o.method == "put" || o.method == "patch" {
				obj = append(obj, kv{"requestBody", omap{{"required", false}, {"content", omap{{"application/json", omap{{"schema", omap{{"type", "object"}}}}}}}}})
			}
			obj = append(obj, kv{"responses", omap{{"200", omap{{"description", "OK"}}}, {"default", omap{{"description", "Error"}}}}})
			obj = append(obj, kv{"x-source", fmt.Sprintf("%s:%d", e.File, e.Line)})
			if e.Handler != "" && !strings.Contains(e.Handler, "func") {
				obj = append(obj, kv{"x-handler", e.Handler})
			}
			obj = append(obj, kv{"x-framework", e.Framework})
			item = append(item, kv{o.method, obj})
		}
		pathObj = append(pathObj, kv{p, item})
	}
	tagList := make([]string, 0, len(tags))
	for t := range tags {
		tagList = append(tagList, t)
	}
	sort.Strings(tagList)
	tagObjs := make([]omap, 0, len(tagList))
	for _, t := range tagList {
		tagObjs = append(tagObjs, omap{{"name", t}})
	}
	return omap{
		{"openapi", "3.1.0"},
		{"info", omap{{"title", res.Name + " API"}, {"version", version},
			{"description", "Generated by Pocket Blueprint from the routes in the code and the API documents in the folder. Paths, methods and path parameters are read from the code; request and response bodies are not described."}}},
		{"tags", tagObjs},
		{"paths", pathObj},
	}
}

func contains(list []string, v string) bool { return indexOf(list, v) >= 0 }

func indexOf(list []string, v string) int {
	for i, x := range list {
		if x == v {
			return i
		}
	}
	return -1
}

var nonWord = regexp.MustCompile(`[^A-Za-z0-9]+`)

// operationID is the handler's name when there is one, else method + path.
func operationID(method string, e analyze.Endpoint) string {
	h := e.Handler
	if i := strings.LastIndexAny(h, ".:"); i >= 0 {
		h = h[i+1:]
	}
	h = nonWord.ReplaceAllString(h, "")
	if h != "" && len(h) <= 60 && !strings.Contains(e.Handler, "func") {
		return h
	}
	parts := nonWord.Split(strings.ToLower(method+" "+paramRe.ReplaceAllString(e.Path, "by $1")), -1)
	var b strings.Builder
	for i, p := range parts {
		if p == "" {
			continue
		}
		if i == 0 {
			b.WriteString(p)
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	return b.String()
}

// tagFor groups by the first path segment that is not api / a version.
func tagFor(p string) string {
	for _, seg := range strings.Split(strings.Trim(p, "/"), "/") {
		if seg == "" || seg == "api" || strings.HasPrefix(seg, "{") || regexp.MustCompile(`^v\d+$`).MatchString(seg) {
			continue
		}
		return seg
	}
	return ""
}

func (s *Server) handleOpenAPI(w http.ResponseWriter, r *http.Request) {
	sc, res, ok := s.scanFor(w, r)
	if !ok {
		return
	}
	version := sc.Commit
	if version == "" {
		version = strings.SplitN(sc.FinishedAt, "T", 2)[0]
	}
	doc := s.openAPI(res, version, r.URL.Query().Get("source"))
	name := safeName(res.Name) + "-openapi"
	if strings.HasSuffix(r.URL.Path, ".yaml") {
		w.Header().Set("Content-Type", "application/yaml; charset=utf-8")
		if queryBool(r, "download") {
			w.Header().Set("Content-Disposition", `attachment; filename="`+name+`.yaml"`)
		}
		var b bytes.Buffer
		writeYAML(&b, doc, 0, false)
		_, _ = w.Write(b.Bytes())
		return
	}
	if queryBool(r, "download") {
		w.Header().Set("Content-Disposition", `attachment; filename="`+name+`.json"`)
	}
	w.Header().Set("Content-Type", "application/json; charset=utf-8")
	enc := json.NewEncoder(w)
	enc.SetIndent("", "  ")
	_ = enc.Encode(doc)
}

// ---- a small YAML writer (enough for the document above) ----

func writeYAML(b *bytes.Buffer, v any, indent int, inList bool) {
	pad := strings.Repeat("  ", indent)
	switch x := v.(type) {
	case omap:
		if len(x) == 0 {
			b.WriteString(" {}\n")
			return
		}
		if !inList {
			b.WriteByte('\n')
		}
		for i, e := range x {
			if !(inList && i == 0) {
				b.WriteString(pad)
			}
			b.WriteString(yamlKey(e.k) + ":")
			writeYAML(b, e.v, indent+1, false)
		}
	case []omap:
		if len(x) == 0 {
			b.WriteString(" []\n")
			return
		}
		b.WriteByte('\n')
		for _, m := range x {
			b.WriteString(pad + "- ")
			writeYAML(b, m, indent+1, true)
		}
	case []string:
		if len(x) == 0 {
			b.WriteString(" []\n")
			return
		}
		b.WriteByte('\n')
		for _, item := range x {
			b.WriteString(pad + "- " + yamlScalar(item) + "\n")
		}
	case string:
		b.WriteString(" " + yamlScalar(x) + "\n")
	case bool:
		b.WriteString(" " + strconv.FormatBool(x) + "\n")
	case int:
		b.WriteString(" " + strconv.Itoa(x) + "\n")
	default:
		j, _ := json.Marshal(x)
		b.WriteString(" " + string(j) + "\n")
	}
}

var plainYAML = regexp.MustCompile(`^[A-Za-z0-9_/][A-Za-z0-9_ ./{}()-]*$`)

func yamlKey(k string) string {
	if _, err := strconv.ParseFloat(k, 64); err != nil && plainYAML.MatchString(k) && !strings.HasSuffix(k, " ") {
		return k
	}
	j, _ := json.Marshal(k)
	return string(j)
}

func yamlScalar(s string) string {
	switch strings.ToLower(s) {
	case "", "true", "false", "null", "yes", "no", "on", "off", "~":
		j, _ := json.Marshal(s)
		return string(j)
	}
	if plainYAML.MatchString(s) && !strings.Contains(s, ": ") && !strings.HasSuffix(s, " ") {
		if _, err := strconv.ParseFloat(s, 64); err != nil {
			return s
		}
	}
	j, _ := json.Marshal(s)
	return string(j)
}
